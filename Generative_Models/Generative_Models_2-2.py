def split_xy(x, y, train_split):
    """
    Splits x and y into training and test sets based on the train split ratio using train_test_split.

    Parameters:
        x (np.ndarray): Input features.
        y (np.ndarray): Target values.
        train_split (float): Proportion of data to be used for training (e.g., 0.9 for 90%).

    Returns:
        tuple: x_train, x_test, y_train, y_test
    """
    if not 0 < train_split < 1:
        raise ValueError("train_split must be a float between 0 and 1 (exclusive).")

    x_train, x_test, y_train, y_test = train_test_split(x, y, train_size=train_split, random_state=None, shuffle=True)
    return x_train, x_test, y_train, y_test

def augment_data(X, y, multiplier):
    """
    Augments the dataset by replicating it based on the multiplier.

    Parameters:
        X (numpy array): Input data (e.g., one-hot encoded equations).
        y (numpy array): Target data (e.g., sequence of images).
        multiplier (int): The factor by which to enlarge the dataset.

    Returns:
        X_augmented (numpy array): Augmented input data.
        y_augmented (numpy array): Augmented target data.
    """
    # Check if multiplier is an integer
    if not isinstance(multiplier, int) or multiplier <= 0:
        raise ValueError("Multiplier must be a positive integer.")

    # Replicating the dataset
    X_augmented = np.tile(X, (multiplier, 1, 1))  # Replicate the data
    y_augmented = np.tile(y, (multiplier, 1, 1, 1))  # Replicate the target sequence of images

    return X_augmented, y_augmented



class EpochEndPredictor(Callback):
    def __init__(self, sample_indices, x_train, y_train, decode_labels):
        """
        Custom callback to make the model predict on specific training samples after each epoch.

        Args:
            sample_indices (list of int): Indices of the samples in the training data.
            x_train (np.ndarray): Training data.
            y_train (np.ndarray): Ground truth labels for the training data.
            decode_labels (function): Function to decode the label (e.g., text query).
        """
        super(EpochEndPredictor, self).__init__()
        self.sample_indices = sample_indices
        self.x_samples = x_train[sample_indices]  # Extract the specific samples
        self.y_samples = y_train[sample_indices]
        self.decode_labels = decode_labels  # Store the decode function

    def on_epoch_end(self, epoch, logs=None):
        print(f"\nEpoch {epoch + 1} predictions:")

        # Create a figure to plot 3 images (3 columns for each sample)
        plt.figure(figsize=(12, 4))

        for i, (x_sample, y_sample) in enumerate(zip(self.x_samples, self.y_samples)):
            # Predict on the sample (reshape if necessary)
            x_sample = x_sample[np.newaxis, :]  # Add batch dimension to shape (1, 5, 13) if needed
            prediction = self.model.predict(x_sample, verbose=0)  # Prediction shape (1, 5, 28, 28)

            # Decode the text query for the current sample
            decoded_query = self.decode_labels(self.x_samples[i])  # Use decode_labels function

            # Plot the predictions for each time step (sequence of 3 images)
            for t in range(3):  # Plot the first 3 time steps
                plt.subplot(1, 3, t + 1)  # Create subplots for 3 images
                plt.imshow(prediction[0][t], cmap='gray')  # Plot the 28x28 image for time step t
                plt.axis('off')  # Hide the axes
                plt.title(f"{decoded_query}")  # Print the decoded text query on the title

        plt.tight_layout()
        plt.show()

