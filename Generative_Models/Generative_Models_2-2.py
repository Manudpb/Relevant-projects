def texttoimage_separate():
    input_layer = Input(shape=(None, len(unique_characters)))
    x = LSTM(512, return_sequences=True)(input_layer)
    x = LSTM(784, return_sequences=False)(x)

    # Digit 1 branch
    digit_1 = Dense(784,activation='relu')(x)
    digit_1 = Reshape((28, 28, 1))(digit_1)
    digit_1 = Conv2DTranspose(128, (3, 3), strides=(1, 1), padding='same', activation='relu')(digit_1)
    digit_1 = Conv2DTranspose(64, (3, 3), strides=(1, 1), padding='same', activation='relu')(digit_1)
    digit_1 = Conv2DTranspose(64, (3, 3), strides=(1, 1), padding='same', activation='relu')(digit_1)
    digit_1 = Conv2DTranspose(1, (3, 3), padding='same', activation='sigmoid')(digit_1)

    # Digit 2 branch
    digit_2 = Dense(784,activation='relu')(x)
    digit_2 = Reshape((28, 28, 1))(digit_2)
    digit_2 = Conv2DTranspose(128, (3, 3), strides=(1, 1), padding='same', activation='relu')(digit_2)
    digit_2 = Conv2DTranspose(64, (3, 3), strides=(1, 1), padding='same', activation='relu')(digit_2)
    digit_2 = Conv2DTranspose(64, (3, 3), strides=(1, 1), padding='same', activation='relu')(digit_2)
    digit_2 = Conv2DTranspose(1, (3, 3), padding='same', activation='sigmoid')(digit_2)

    # Digit 3 branch
    digit_3 = Dense(784,activation='relu')(x)
    digit_3 = Reshape((28, 28, 1))(digit_3)
    digit_3 = Conv2DTranspose(128, (3, 3), strides=(1, 1), padding='same', activation='relu')(digit_3)
    digit_3 = Conv2DTranspose(64, (3, 3), strides=(1, 1), padding='same', activation='relu')(digit_3)
    digit_3 = Conv2DTranspose(64, (3, 3), strides=(1, 1), padding='same', activation='relu')(digit_3)
    digit_3 = Conv2DTranspose(1, (3, 3), padding='same', activation='sigmoid')(digit_3)

    # Model compilation
    model = Model(inputs=input_layer, outputs=[digit_1, digit_2, digit_3])
    model.compile(
    loss=['binary_crossentropy', 'binary_crossentropy', 'binary_crossentropy'],  # One loss per output
    optimizer='adam',
    metrics=[['accuracy'], ['accuracy'], ['accuracy']]  # One metric list per output
    )
    model.summary()
    return model

