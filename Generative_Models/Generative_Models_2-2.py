# 2 part model separated text encoding part and image decoder part
def two_part_text_to_image(t2t):
    # Extract the first LSTM layer (encoder part)
    encoder_layer = t2t.layers[0]

    # Freeze the encoder's first LSTM layer
    encoder_layer.trainable = False

    # Define the new text-to-image model
    tti = tf.keras.Sequential()

    # Add the pre-trained encoder (only the first LSTM layer) to the new model
    tti.add(encoder_layer)

    # Add RepeatVector to repeat the vector 3 times to create a sequence
    tti.add(RepeatVector(3))

    # Add TimeDistributed Dense layer for latent space projection (to output 784, which represents 28x28 images)
    tti.add(TimeDistributed(Dense(784, activation='relu')))  # Flattened 28x28 image (784)

    # Reshape the 784-dim vector into a 28x28 image (using TimeDistributed)
    tti.add(TimeDistributed(Reshape((28, 28, 1))))  # Reshape to 28x28x1 image

    # Add transposed convolution layers (Conv2DTranspose) to generate images from the latent vector
    tti.add(TimeDistributed(Conv2DTranspose(128, (3, 3), strides=(1, 1), padding='same', activation='relu')))
    tti.add(TimeDistributed(Conv2DTranspose(64, (3, 3), strides=(1, 1), padding='same', activation='relu')))

    # Final output layer to generate a 28x28 image for each time step
    tti.add(TimeDistributed(Conv2DTranspose(1, (3, 3), padding='same', activation='sigmoid')))

    # Add ConvLSTM2D layer (for sequence generation)
    tti.add(ConvLSTM2D(filters=1, kernel_size=(3, 3), strides=(1, 1), return_sequences=True, padding='same'))

    # Compile the model
    tti.compile(loss='binary_crossentropy', optimizer='adam', metrics=['accuracy'])

    # Print the model summary
    tti.summary()

    return tti

